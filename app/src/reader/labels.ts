// Wiktionary splits a qualified variety into two tags; Italian puts the qualifier after.
const TAG_PAIRS: Record<string, string> = {
  "Middle Polish": "polacco medio",
  "Eastern Galicia": "Galizia orientale",
};

export function italianTags(tags: string[]): string {
  const t = tags.filter((x) => !x.startsWith("error-"));
  const out: string[] = [];
  for (let i = 0; i < t.length; i++) {
    const pair = TAG_PAIRS[`${t[i]} ${t[i + 1]}`];
    if (pair) {
      out.push(pair);
      i++;
    } else {
      out.push(TAGS[t[i]] ?? t[i].replaceAll("-", " "));
    }
  }
  return out.join(" ");
}

/** A dictionary form's case, shown as a pill, and its other tags. */
export function caseOfForm(tags: string[]): {
  pill: { key: CaseKey; label: string } | null;
  rest: string[];
} {
  const tag = tags.find((x) => CASES[x]);
  if (!tag) return { pill: null, rest: tags };
  const key = CASES[tag];
  return { pill: { key, label: CASE_NAMES[key].it }, rest: tags.filter((x) => x !== tag) };
}
